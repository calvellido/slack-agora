import { availableLanguages, callerParams, loadCatalog, messageParams, type Catalog } from './catalog.ts';

// Turns the English texts into the Strings type that code uses, and checks the other languages against them.

/** src/i18n/messages.ts: one property per text, a function when the text takes values. */
export function generateTypes(english: Catalog): string {
  type Tree = { [key: string]: Tree | string };
  const tree: Tree = {};
  for (const [key, message] of english) {
    const path = key.split('.');
    let node = tree;
    for (const part of path.slice(0, -1)) node = (node[part] ??= {}) as Tree;
    const params = [...callerParams(message)].map(([name, type]) => `${name}: ${type}`);
    node[path.at(-1)!] = params.length ? `(params: { ${params.join('; ')} }) => string` : 'string';
  }
  const render = (node: Tree, indent: string): string =>
    Object.entries(node)
      .map(([key, value]) =>
        typeof value === 'string' ? `${indent}${key}: ${value};\n` : `${indent}${key}: {\n${render(value, indent + '  ')}${indent}};\n`,
      )
      .join('');
  return (
    "// Generated by `pnpm i18n` from locales/en.yml. Don't edit it by hand.\n\n" +
    '/** Every text, in the shape of locales/en.yml. Texts that take values are functions. */\n' +
    `export interface Strings {\n${render(tree, '  ')}}\n`
  );
}

export interface Report {
  /** Problems that would break the bot or show a wrong text. */
  errors: string[];
  /** Texts a language doesn't translate yet; it shows the English ones. */
  missing: Map<string, string[]>;
}

/** Checks every language against English: valid messages, known keys, the same values. */
export function check(languages = availableLanguages(), load: (language: string) => Catalog = loadCatalog): Report {
  const errors: string[] = [];
  const missing = new Map<string, string[]>();
  const english = load('en');
  for (const [key, message] of english) {
    try {
      messageParams(message);
    } catch (error) {
      errors.push(`en: ${key} is not a valid message (${(error as Error).message})`);
    }
  }
  for (const language of languages.filter((l) => l !== 'en')) {
    const catalog = load(language);
    missing.set(language, [...english.keys()].filter((key) => !catalog.has(key)));
    for (const [key, message] of catalog) {
      const reference = english.get(key);
      if (reference === undefined) {
        errors.push(`${language}: ${key} doesn't exist in English`);
        continue;
      }
      let own: string, expected: string;
      try {
        own = describe(callerParams(message));
        expected = describe(callerParams(reference));
      } catch (error) {
        errors.push(`${language}: ${key} is not a valid message (${(error as Error).message})`);
        continue;
      }
      if (own !== expected) errors.push(`${language}: ${key} takes {${own}}, but English takes {${expected}}`);
    }
  }
  return { errors, missing };
}

function describe(params: Map<string, string>): string {
  return [...params].map(([name, type]) => `${name}: ${type}`).sort().join(', ');
}
